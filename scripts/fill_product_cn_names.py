db = SessionLocal()

# 先去重（保序）
seen = set()
dedup = []
for offer, cn in MAPPING:
    if offer not in seen:
        seen.add(offer)
        dedup.append((offer, cn))

updated = 0
not_found_products = []
no_sku_mgmt = []

for offer, cn in dedup:
    # offer_id -> product -> sku_id
    prods = db.query(Product).filter(Product.offer_id == offer).all()
    if not prods:
        not_found_products.append(offer)
        continue

    for p in prods:
        mgmt = db.query(SkuManagement).filter_by(store_id=p.store_id, sku_id=p.sku_id).first()
        if mgmt is None:
            no_sku_mgmt.append((offer, p.store_id, p.sku_id))
            continue
        mgmt.product_cn_name = cn
        updated += 1

db.commit()
db.close()

print(f"Total unique offer_ids: {len(dedup)}")
print(f"Updated sku_management records: {updated}")
if not_found_products:
    print(f"\n=== offer_id 在 products 表未找到 ({len(not_found_products)}) ===")
    for o in not_found_products:
        print(f"  {o}")
if no_sku_mgmt:
    print(f"\n=== 有 product 但无 sku_management 记录 ({len(no_sku_mgmt)}) ===")
    for o, s, sku in no_sku_mgmt:
        print(f"  {o} (store={s}, sku={sku})")
